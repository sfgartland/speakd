import { describe, expect, it } from "vitest";
import { tagSegments } from "../src/footnotes";
import { matchLabels, parseLabelFile } from "../src/labelstore";
import { scoreFixture } from "../src/scoring";
import footnotesDump from "./fixtures/footnotes.jsonl?raw";
import { buildParts } from "../src/export/parts";
import kohlerCapture from "./fixtures/pdf/kohler/capture.jsonl?raw";
import kohlerLabels from "./fixtures/pdf/kohler/labels.json?raw";
import syntheticCapture from "./fixtures/pdf/synthetic/capture.jsonl?raw";
import syntheticLabels from "./fixtures/pdf/synthetic/labels.json?raw";
import twocolumnDump from "./fixtures/twocolumn.jsonl?raw";

// The checked-in harness dumps (clients/zotero/test/fixtures/README.md): the
// real segments Zotero's SDT worker produced for the shared corpus. They let
// the filters be tested against real capture shape, rects and all, without a
// live harness.

interface DumpSegment {
  readonly text: string;
  readonly pageIndex: number | null;
  readonly anchor: string | null;
  readonly firstRectY: number | null;
}

function parse(raw: string): DumpSegment[] {
  return raw
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map((line) => JSON.parse(line) as DumpSegment)
    .filter((entry) => typeof entry.text === "string");
}

describe("the checked-in segment dumps", () => {
  it("tags the footnote dump: citations dropped, the year-led body line kept", () => {
    const segments = parse(footnotesDump);
    const { tagged, dropped } = tagSegments(segments, "classify");
    expect(tagged).toHaveLength(segments.length);
    expect(dropped.length).toBeGreaterThan(0);
    // No body paragraph is ever dropped: only footnote lines and, where the
    // fixture repeats one verbatim as a page's last segment, its recurring
    // tail. Every drop is in the audit list.
    expect(dropped.some((entry) => /^P\d+ L\d/.test(entry.text))).toBe(false);
    expect(dropped.some((entry) => entry.why === "footnote")).toBe(true);
    // The body line that opens with a year sits in the body band: kept.
    const year = tagged.find((segment) => segment.text.includes("1994 was the year"));
    expect(year?.tag).not.toBe("drop");
    // No citation footnote is read in place.
    const spoken = tagged
      .filter((segment) => segment.tag !== "drop")
      .map((segment) => segment.text)
      .join(" ");
    expect(spoken).not.toContain("Kant, KrV");
    expect(spoken).not.toContain("op. cit.");
  });

  it("keeps the two-column dump's reading order and the planted cross sentence adjacent", () => {
    const segments = parse(twocolumnDump);
    const { tagged } = tagSegments(segments, "classify");
    const kept = tagged.filter((segment) => segment.tag !== "drop");
    const first = kept.findIndex((segment) => segment.text.startsWith("The cross column sentence begins"));
    expect(first).toBeGreaterThanOrEqual(0);
    expect(kept[first + 1]?.text).toContain("and ends in the rightmost column.");
    expect(kept.map((segment) => segment.text).join(" ")).not.toContain("A Tale of Two Columns");
  });
});

// The checked-in synthetic label fixture, generated by the exporter's own
// `fixtureContent` (spec §8.3). It is consumed twice: unaided, documenting
// the rules' failure as the characterisation, and with the labels, documenting
// the fix. The unaided score is asserted against the fixture's known misses
// and over-drops.
describe("the synthetic label fixture", () => {
  const segments = parse(syntheticCapture);
  const parsed = parseLabelFile(syntheticLabels);

  it("round-trips: every label still matches its capture", () => {
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    const { overrides, unmatched } = matchLabels(parsed.file, segments);
    expect(overrides.size).toBe(20);
    expect(unmatched).toEqual([]);
  });

  it("documents the unaided rules' failure and scores it", () => {
    if (!parsed.ok) throw new Error("the fixture's labels are unparsable");
    const { overrides } = matchLabels(parsed.file, segments);
    const labels = [...overrides].map(([index, category]) => ({ index, category }));
    const score = scoreFixture(segments, labels, tagSegments(segments, "classify").tagged);
    expect(score.misses).toHaveLength(5); // the undetected footnotes
    expect(score.overDrops).toHaveLength(5); // the recurring body paragraph
    expect(score.footnoteDetected).toBe(0);
    expect(score.footnoteTotal).toBe(5);
    expect(score.precision).toBeCloseTo(0.5);
    expect(score.recall).toBeCloseTo(0.5);
  });

  it("documents the fix when the labels are applied", () => {
    if (!parsed.ok) throw new Error("the fixture's labels are unparsable");
    const { overrides } = matchLabels(parsed.file, segments);
    const unaided = tagSegments(segments, "classify").tagged;
    const withLabels = tagSegments(segments, "classify", overrides).tagged;
    for (const [index, category] of overrides) {
      if (category === "running-head" || category === "footnote") {
        expect(withLabels[index]?.tag).not.toBe("body");
      }
      if (category === "body" && unaided[index]?.tag === "drop") {
        expect(withLabels[index]?.tag).toBe("body");
      }
    }
  });
});

// The real Köhler fixture (spec §8.5): pages 34-38, derived artifacts only,
// the PDF never checked in. Its one labelable failure is the OCR'd inline
// footnote; the running heads and page numbers were dropped before the
// capture, so they are named in the README's gap report and cannot be
// labelled. The unaided rules already detect the footnote, so the score is
// clean: the real debt is the pre-capture gap.
describe("the Köhler fixture", () => {
  const segments = parse(kohlerCapture);
  const parsed = parseLabelFile(kohlerLabels);

  it("matches its one label, the inline footnote, and detects it unaided", () => {
    if (!parsed.ok) throw new Error("the fixture's labels are unparsable");
    const { overrides, unmatched } = matchLabels(parsed.file, segments);
    expect(overrides.size).toBe(1);
    expect([...overrides.values()]).toEqual(["footnote"]);
    expect(unmatched).toEqual([]);
    const labels = [...overrides].map(([index, category]) => ({ index, category }));
    const score = scoreFixture(segments, labels, tagSegments(segments, "classify").tagged);
    expect(score.footnoteDetected).toBe(1);
    expect(score.footnoteTotal).toBe(1);
    expect(score.misses).toEqual([]);
    expect(score.overDrops).toEqual([]);
    expect(score.precision).toBe(1);
    expect(score.recall).toBe(1);
  });

  it("keeps the labelled footnote out of the body flow, at the part's end", () => {
    if (!parsed.ok) throw new Error("the fixture's labels are unparsable");
    const { overrides } = matchLabels(parsed.file, segments);
    const parts = buildParts(
      segments.map((segment) => ({ ...segment, pageIndex: segment.pageIndex ?? 0 })),
      "Köhler",
      { kind: "pages", ranges: [{ startPage: 34, endPage: 38 }] },
      { footnotes: "classify", overrides },
    );
    expect(parts).toHaveLength(1);
    expect(parts[0]?.text.trimEnd().endsWith("which they express.")).toBe(true);
  });
});
